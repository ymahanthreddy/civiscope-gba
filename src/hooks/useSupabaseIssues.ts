import { useState, useEffect, useCallback } from 'react';
import { supabase } from '@/integrations/supabase/client';
import type { Tables, TablesInsert } from '@/integrations/supabase/types';
import { toast } from '@/hooks/use-toast';

export type Issue = Tables<'issues'>;
export type Official = Tables<'officials'>;
export type IssueStatus = 'reported' | 'assigned' | 'in_progress' | 'closed' | 'escalated';
export type IssueCategory = 'garbage' | 'roads' | 'drainage' | 'streetlights' | 'parks' | 'stray_dogs';

export function useSupabaseIssues() {
  const [issues, setIssues] = useState<Issue[]>([]);
  const [officials, setOfficials] = useState<Official[]>([]);
  const [loading, setLoading] = useState(true);

  const fetchIssues = useCallback(async () => {
    const { data, error } = await supabase
      .from('issues')
      .select('*')
      .order('created_at', { ascending: false });

    if (error) {
      console.error('Error fetching issues:', error);
      toast({
        title: 'Error',
        description: 'Failed to fetch issues',
        variant: 'destructive',
      });
    } else {
      setIssues(data || []);
    }
  }, []);

  const fetchOfficials = useCallback(async () => {
    const { data, error } = await supabase
      .from('officials')
      .select('*');

    if (error) {
      console.error('Error fetching officials:', error);
    } else {
      setOfficials(data || []);
    }
  }, []);

  useEffect(() => {
    const loadData = async () => {
      setLoading(true);
      await Promise.all([fetchIssues(), fetchOfficials()]);
      setLoading(false);
    };
    loadData();

    // Subscribe to realtime changes
    const channelName = `issues-changes-${Date.now()}`;
    const channel = supabase
      .channel(channelName)
      .on(
        'postgres_changes',
        { event: '*', schema: 'public', table: 'issues' },
        () => {
          fetchIssues();
        }
      )
      .subscribe();

    return () => {
      supabase.removeChannel(channel);
    };
  }, [fetchIssues, fetchOfficials]);

  const addIssue = async (issueData: {
    category: IssueCategory;
    description: string;
    location: string;
    area?: string;
    reporter_name: string;
    reporter_contact: string;
    image_url?: string;
    user_id?: string;
  }): Promise<string | null> => {
    const { data, error } = await supabase
      .from('issues')
      .insert({
        category: issueData.category,
        description: issueData.description,
        location: issueData.location,
        area: issueData.area,
        reporter_name: issueData.reporter_name,
        reporter_contact: issueData.reporter_contact,
        image_url: issueData.image_url,
        user_id: issueData.user_id,
        tracking_id: '', // Will be auto-generated by trigger
      })
      .select()
      .single();

    if (error) {
      console.error('Error adding issue:', error);
      toast({
        title: 'Error',
        description: 'Failed to submit issue',
        variant: 'destructive',
      });
      return null;
    }

    // Trigger AI auto-assignment in background
    try {
      const autoAssignResponse = await supabase.functions.invoke('auto-assign-issue', {
        body: {
          issueId: data.id,
          category: issueData.category,
          description: issueData.description,
          location: issueData.location,
        }
      });
      
      if (autoAssignResponse.data?.success) {
        console.log('AI Auto-assignment:', autoAssignResponse.data.message);
        toast({
          title: 'Issue Reported Successfully! 🎉',
          description: `Tracking ID: ${data.tracking_id} • AI assigned to ${autoAssignResponse.data.assignedTo}`,
        });
      } else {
        toast({
          title: 'Issue Reported Successfully! 🎉',
          description: `Your tracking ID is ${data.tracking_id}`,
        });
      }
    } catch (aiError) {
      console.error('AI auto-assign error:', aiError);
      toast({
        title: 'Issue Reported Successfully! 🎉',
        description: `Your tracking ID is ${data.tracking_id}`,
      });
    }

    return data.tracking_id;
  };

  const getIssueByTrackingId = async (trackingId: string): Promise<Issue | null> => {
    const { data, error } = await supabase
      .from('issues')
      .select('*')
      .ilike('tracking_id', trackingId)
      .maybeSingle();

    if (error) {
      console.error('Error fetching issue:', error);
      return null;
    }

    return data;
  };

  const updateIssueStatus = async (id: string, status: IssueStatus): Promise<boolean> => {
    const updateData: Partial<Issue> = { status };
    if (status === 'closed') {
      updateData.closed_at = new Date().toISOString();
    }

    const { error } = await supabase
      .from('issues')
      .update(updateData)
      .eq('id', id);

    if (error) {
      console.error('Error updating status:', error);
      toast({
        title: 'Error',
        description: 'Failed to update status',
        variant: 'destructive',
      });
      return false;
    }

    toast({
      title: 'Status Updated',
      description: `Issue status changed to ${status}`,
    });

    return true;
  };

  const assignIssue = async (id: string, officialName: string): Promise<boolean> => {
    const { error } = await supabase
      .from('issues')
      .update({ 
        assigned_to: officialName,
        status: 'assigned' as IssueStatus
      })
      .eq('id', id);

    if (error) {
      console.error('Error assigning issue:', error);
      toast({
        title: 'Error',
        description: 'Failed to assign issue',
        variant: 'destructive',
      });
      return false;
    }

    toast({
      title: 'Issue Assigned',
      description: `Issue assigned to ${officialName}`,
    });

    return true;
  };

  const closeIssue = async (id: string, resolutionNotes: string, resolutionImage?: string): Promise<boolean> => {
    const { error } = await supabase
      .from('issues')
      .update({ 
        status: 'closed' as IssueStatus,
        resolution_notes: resolutionNotes,
        resolution_image: resolutionImage,
        closed_at: new Date().toISOString()
      })
      .eq('id', id);

    if (error) {
      console.error('Error closing issue:', error);
      toast({
        title: 'Error',
        description: 'Failed to close issue',
        variant: 'destructive',
      });
      return false;
    }

    toast({
      title: 'Issue Resolved! 🎉',
      description: 'The issue has been marked as closed',
    });

    return true;
  };

  const escalateIssue = async (id: string): Promise<boolean> => {
    const { error } = await supabase
      .from('issues')
      .update({ status: 'escalated' as IssueStatus })
      .eq('id', id);

    if (error) {
      console.error('Error escalating issue:', error);
      toast({
        title: 'Error',
        description: 'Failed to escalate issue',
        variant: 'destructive',
      });
      return false;
    }

    toast({
      title: 'Issue Escalated! ⚠️',
      description: 'This issue has been marked for urgent attention',
    });

    return true;
  };

  return {
    issues,
    officials,
    loading,
    addIssue,
    getIssueByTrackingId,
    updateIssueStatus,
    assignIssue,
    closeIssue,
    escalateIssue,
    refetch: fetchIssues,
  };
}
